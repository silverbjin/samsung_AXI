#!/usr/bin/env python3
"""B-DATA-QA-01 SHA-pinned, private, off-line audit runner. No ROS or AI training."""
from __future__ import annotations
import argparse
import datetime as dt
import hashlib
import io
import json
import os
import re
import secrets
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

from audit_b_dacon_qa01 import stage_audit, QAError, verified_archive, A13_SHA, sha_file

MAX_PACKAGE_BYTES=32*1024*1024
MAX_FILES=80

class CliError(ValueError):pass

class Parser(argparse.ArgumentParser):
    def error(self,message):raise CliError('B_QA_CLI_ARGS_INVALID '+message)

def sha_pin(root:Path, expected:str):
    if not re.fullmatch(r'[0-9a-f]{40}',expected):raise CliError('B_QA_CODE_SHA_INVALID')
    g=subprocess.run(['git','-C',str(root),'rev-parse','HEAD'],capture_output=True,text=True)
    if g.returncode or g.stdout.strip()!=expected:raise CliError('B_QA_CODE_SHA_PIN_MISMATCH')
    status=subprocess.run(['git','-C',str(root),'status','--porcelain','--untracked-files=no'],capture_output=True,text=True)
    if status.returncode or status.stdout.strip():raise CliError('B_QA_TRACKED_WORKTREE_DIRTY')

def resolve_workspace(root:Path, requested:str|None):
    if requested: p=Path(requested).expanduser().absolute()
    else:
        parent=root/'ai/data/private'
        candidates=sorted((p for p in parent.glob('b12_operator_review_*') if p.is_dir() and (p/'review/candidate_manifest.csv').is_file()),
                          key=lambda p:(p.stat().st_mtime_ns,p.name),reverse=True) if parent.exists() else []
        if not candidates:raise CliError('B_QA_WORKSPACE_NOT_FOUND')
        p=candidates[0]
    if not p.is_dir() or not (p/'raw').is_dir() or not (p/'review').is_dir():
        raise CliError('B_QA_WORKSPACE_INVALID')
    return p

def find_source(root:Path,requested:str|None):
    if requested:
        p=Path(requested).expanduser().absolute()
        if not p.is_file():raise CliError('B_Q01_ORIGINAL_TAR_NOT_FOUND')
        return p
    sources=[Path.home()/'samsung_AXI_A_TRAY/generated/smartdish_tray',root/'ai/data/private/source_a13']
    for base in sources:
        if not base.is_dir():continue
        for p in sorted(base.glob('**/smartdish_a_tray_evidence*.gz')):
            if len(p.relative_to(base).parts)>7 or not p.is_file() or p.is_symlink():continue
            # Never accept a similarly named but unrelated source based on filename alone.
            if p.stat().st_size <= 600*1024*1024 and sha_file(p)==A13_SHA:return p
    return None  # fail-closed Q01 HOLD rather than inventing provenance

def pack_summary(folder:Path,output:Path,status:dict,log:str):
    if output.exists():raise CliError('B_QA_DIAGNOSTIC_NO_OVERWRITE')
    files={'diagnostic_status.json':(json.dumps(status,ensure_ascii=False,indent=2)+'\n').encode(),
           'execution.log':log.encode()}
    qa=folder/'qa'
    if qa.is_dir():
        for f in sorted(qa.iterdir()):
            if f.is_symlink() or not f.is_file() or f.suffix not in ('.json','.csv','.md','.png'):
                continue
            if f.stat().st_size>10*1024*1024:raise CliError('B_QA_DIAGNOSTIC_MEMBER_LIMIT')
            files['qa/'+f.name]=f.read_bytes()
    if len(files)>MAX_FILES or sum(map(len,files.values()))>MAX_PACKAGE_BYTES:
        raise CliError('B_QA_DIAGNOSTIC_SIZE_LIMIT')
    files['SHA256SUMS']=''.join(hashlib.sha256(data).hexdigest()+'  '+name+'\n' for name,data in files.items()).encode()
    output.parent.mkdir(parents=True,exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=output.parent,prefix='.bqa-',suffix='.tmp',delete=False) as f:
        temp=Path(f.name)
    try:
        with tarfile.open(temp,'w:gz') as t:
            for name,data in files.items():
                info=tarfile.TarInfo(name);info.size=len(data);info.mode=0o600
                info.uid=info.gid=0;info.mtime=0
                t.addfile(info,io.BytesIO(data))
        if output.exists():raise CliError('B_QA_DIAGNOSTIC_NO_OVERWRITE')
        os.replace(temp,output)
        side=Path(str(output)+'.sha256')
        side.write_text(sha_file(output)+'  '+output.name+'\n',encoding='utf-8')
        return {'members':len(files),'sha256':sha_file(output),'sidecar':str(side)}
    finally:temp.unlink(missing_ok=True)

def main(argv=None):
    parser=Parser(description=__doc__)
    parser.add_argument('--sha',required=True)
    parser.add_argument('--workspace',help='existing B12R directory containing raw/ and review/; default autodiscovery')
    parser.add_argument('--source-archive',help='original A13 TAR; optional (missing means B-Q01 HOLD)')
    parser.add_argument('--split-manifest',help='approved split manifest for optional B-Q06 audit')
    parser.add_argument('--release-manifest',help='approved C release manifest (not generated by QA)')
    parser.add_argument('--mode',choices=('audit',),default='audit')
    parser.add_argument('--help-preserve',action='store_true',help=argparse.SUPPRESS)
    if argv is None:argv=sys.argv[1:]
    if '--help' in argv or '-h' in argv:parser.print_help();return 0
    root=Path(__file__).resolve().parents[2]
    os.umask(0o077)
    token=dt.datetime.now(dt.timezone.utc).strftime('%Y%m%dT%H%M%SZ')+'_'+str(os.getpid())+'_'+secrets.token_hex(3)
    out=root/'ai/data/private/b_dacon_qa01'/token
    out.mkdir(parents=True,exist_ok=False)
    lines=[];rc=0;quality='ERROR';source=None;workspace=None
    try:
        args=parser.parse_args(argv)
        sha_pin(root,args.sha)
        lines.append('B_QA_CODE_SHA_PIN_PASS '+args.sha)
        workspace=resolve_workspace(root,args.workspace)
        source=find_source(root,args.source_archive)
        if source:lines.append('B_QA_A13_SOURCE_TAR_SELECTED sha256='+sha_file(source))
        else:lines.append('B_QA_A13_SOURCE_TAR_NOT_FOUND_Q01_HOLD')
        base=root/'docs/quality/SMARTDISH_B_DACON_DATA_QUALITY_BASELINE_20261125_KO.md'
        result=stage_audit(workspace/'raw',workspace/'review',out/'qa',source_archive=source,
                           baseline=base if base.is_file() else None,
                           split_manifest=Path(args.split_manifest).expanduser().absolute() if args.split_manifest else None,
                           release_manifest=Path(args.release_manifest).expanduser().absolute() if args.release_manifest else None)
        quality=result['overall'];lines.append('B_DATA_QA01_AUDIT_COMPLETED')
        for k,x in result['gates'].items():lines.append(k+'='+x['status'])
        lines.append('B_DATA_QA01_DATASET_HOLD' if quality=='HOLD' else 'B_DATA_QA01_REVIEW_REQUIRED')
    except (CliError,QAError,OSError,ValueError,KeyError,TypeError) as exc:
        rc=2;lines.append('B_DATA_QA01_FAILED '+str(exc))
    for line in lines:print(line,file=sys.stderr if line.startswith('B_DATA_QA01_FAILED') else sys.stdout,flush=True)
    status={'schema':1,'task':'B-DATA-QA-01','run_status':'AUDIT_COMPLETED' if rc==0 else 'RUN_FAILED',
            'exit_code':rc,'quality_verdict':quality,'code_sha':args.sha if 'args' in locals() else None,
            'source_archive_sha256':sha_file(source) if source and source.is_file() else None,'workspace':str(workspace) if workspace else None,
            'automatic_approval':False,'training_executed':False,
            'created_at_utc':dt.datetime.now(dt.timezone.utc).isoformat()}
    diag=out/'b_dacon_qa01_diagnostics.tar.gz'
    try:
        info=pack_summary(out,diag,status,'\n'.join(lines)+'\n')
        print('B_QA_DIAGNOSTIC_ARCHIVE_CREATED path='+str(diag)+' sha256='+info['sha256']+' members='+str(info['members']))
        print('B_QA_DIAGNOSTIC_SHA256_FILE path='+info['sidecar'])
    except (CliError,OSError,ValueError) as exc:
        print('B_QA_DIAGNOSTIC_ARCHIVE_FAILED '+str(exc),file=sys.stderr)
        (out/'error_status.json').write_text(json.dumps(status,indent=2)+'\n')
        if rc==0:rc=4
    print('B_QA_PRIVATE_RUN_DIR='+str(out))
    return rc

if __name__=='__main__':raise SystemExit(main())
