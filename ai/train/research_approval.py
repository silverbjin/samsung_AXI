"""C V1 explicit human and pretrained-cache gate; real training never auto-starts."""
from __future__ import annotations
import hashlib
import json
from pathlib import Path

from ai.train.dataset_v1_gate import (VERSION, RELEASE_SHA, SPLIT_SHA,
    B_EXEC_SHA, IntakeHold, require, sha_file)


def approve_training(root: Path, split_manifest: Path, approval_file: Path | None,
                     plan_file: Path, *, phase: str, p0_report: Path | None = None) -> dict:
    """Read only; no Model/torch import, no test model-selection access.

    Returns approval metadata *only* after private 42/42 P0 plus explicit C review.
    Approval record is never generated by this tool and stays off GitHub.
    """
    require(approval_file is not None and approval_file.is_file(),
            "C_V1_C_RESEARCH_APPROVAL_REQUIRED")
    require(plan_file.is_file(), "C_V1_P1_PLAN_MISSING")
    plan_bytes = plan_file.read_bytes()
    plan = json.loads(plan_bytes)
    require(plan.get("status") == "PREDECLARED_NOT_APPROVED_TO_TRAIN" and
            plan.get("data", {}).get("version") == VERSION and
            plan.get("execution", {}).get("test_reselection_or_tuning") is False and
            plan.get("execution", {}).get("max_frozen_runs") == 1 and
            plan.get("operational_inference", {}).get("confidence_min") == 0.8,
            "C_V1_P1_PLAN_CONTRACT_INVALID")
    require(phase == "frozen", "C_V1_FINETUNE_NOT_PREAPPROVED")
    approval = json.loads(approval_file.read_text(encoding="utf-8"))
    require(approval.get("decision") == "C_P0_RESEARCH_TRAIN_GO" and
            approval.get("C_independent_files_verified") == 42 and
            approval.get("dataset_version") == VERSION and
            approval.get("B_execution_pin") == B_EXEC_SHA and
            approval.get("release_sha256") == RELEASE_SHA and
            approval.get("split_sha256") == SPLIT_SHA and
            approval.get("experiment_lock_sha256") == hashlib.sha256(plan_bytes).hexdigest() and
            isinstance(approval.get("reviewer"), str) and bool(approval["reviewer"].strip()) and
            approval.get("pretrained_license_reviewed") is True,
            "C_V1_C_RESEARCH_APPROVAL_INVALID")
    expected_weight = approval.get("pretrained_weight_sha256")
    require(isinstance(expected_weight, str) and len(expected_weight) == 64 and
            all(c in "0123456789abcdef" for c in expected_weight),
            "C_V1_PRETRAINED_FULL_SHA_REQUIRED")
    require(sha_file(split_manifest) == SPLIT_SHA,
            "C_V1_SPLIT_SHA_MISMATCH_BEFORE_TRAIN")
    # Never open or hash Test pixels inside the P2 training process. P0 ran
    # independently, verified all 42 in a separate immutable read-only run.
    require(p0_report is not None and p0_report.is_file(),
            "C_V1_INDEPENDENT_P0_REPORT_REQUIRED")
    p0 = json.loads(p0_report.read_text(encoding="utf-8"))
    require(approval.get("p0_report_sha256") == sha_file(p0_report) and
            p0.get("verdict") == "CONTRACT_READY_HUMAN_REVIEW_REQUIRED" and
            p0.get("files_independently_hashed") == 42 and
            p0.get("dataset_version") == VERSION and
            p0.get("training_executed") is False,
            "C_V1_INDEPENDENT_P0_REPORT_INVALID")
    # Do not fetch weights silently. Explicitly validate a fixed cached V1 file.
    try:
        from torch.hub import get_dir
        from torchvision.models import ResNet18_Weights
    except ImportError as exc:
        raise IntakeHold("C_V1_TORCHVISION_NOT_INSTALLED") from exc
    enum = ResNet18_Weights.IMAGENET1K_V1
    cached = Path(get_dir()) / "checkpoints" / enum.url.rsplit("/", 1)[-1]
    require(cached.is_file(), "C_V1_PRETRAINED_CACHE_MISSING")
    require(sha_file(cached) == expected_weight,
            "C_V1_PRETRAINED_FULL_SHA_MISMATCH")
    return {"C_P0_research_approval": "GO", "plan_sha256": hashlib.sha256(plan_bytes).hexdigest(),
            "pretrained_weight_sha256": expected_weight, "dataset_version": VERSION}
